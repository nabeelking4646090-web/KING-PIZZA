// King Pizza Attendance — minimal service worker.
// Its only job is to satisfy the Chrome/Edge PWA "installability"
// requirement (a registered service worker with a fetch handler),
// plus basic offline fallback for pages already visited.
const CACHE_NAME = 'king-pizza-attendance-v1';

self.addEventListener('install', function () {
  self.skipWaiting();
});

self.addEventListener('activate', function (event) {
  event.waitUntil(self.clients.claim());
});

self.addEventListener('fetch', function (event) {
  if (event.request.method !== 'GET') return;
  event.respondWith(
    fetch(event.request)
      .then(function (response) {
        var copy = response.clone();
        caches.open(CACHE_NAME).then(function (cache) {
          cache.put(event.request, copy);
        });
        return response;
      })
      .catch(function () {
        return caches.match(event.request);
      })
  );
});
